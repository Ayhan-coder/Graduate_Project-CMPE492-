"""Build paper/tables/prompt_strategies.tex from a measured strategy run.

Only rows with ``simulated == false`` are publishable. The ``--test`` path of
prompt_strategies.py samples hardcoded slices of the gold list and forces
precision to 1.0, so its F1 values (47.6 / 60.9 / 76.9) are a property of the
mock, not of the model; this script refuses to render them.

Output:
    paper/tables/prompt_strategies.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DEFAULT_IN = ROOT / "outputs" / "prompt_strategies.jsonl"
DEFAULT_OUT = ROOT.parent / "paper" / "tables" / "prompt_strategies.tex"

ORDER = {"zero_shot": 0, "cot": 1, "rag": 2}


def load_rows(path: Path) -> list[dict]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        if rec.get("simulated"):
            raise SystemExit(
                f"{path.name} contains simulated rows (strategy={rec['strategy']}, "
                f"clip={rec['clip']}); re-run without --test before generating a table"
            )
        rows.append(rec)
    rows.sort(key=lambda r: (r["clip"], ORDER.get(r["strategy"], 9)))
    return rows


def fmt(value: float, digits: int = 1) -> str:
    return f"{value:.{digits}f}".rstrip("0").rstrip(".")


def render(rows: list[dict]) -> str:
    lines = [
        "% GENERATED by experiments/make_prompt_strategy_table.py -- do not edit by hand.",
        "% Source: experiments/outputs/prompt_strategies.jsonl (real Qwen3.5-4B calls).",
        "% Mock (--test) rows are rejected by the generator.",
        "\\begin{table}[t]",
        "\\centering",
        "\\renewcommand{\\arraystretch}{1.1}",
        "\\small",
        "\\begin{tabular}{@{}llccccc@{}}",
        "\\toprule",
        "\\textbf{Clip} & \\textbf{Strategy} & \\textbf{Terms} & \\textbf{TP} "
        "& \\textbf{Prec. (\\%)} & \\textbf{Rec. (\\%)} & \\textbf{$F_1$ (\\%)} \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['clip']} & {r['strategy_label']} & {r['n_terms']} & {r['tp']} & "
            f"{fmt(r['precision'])} & {fmt(r['recall'])} & {fmt(r['f1'])} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append(
        "\\multicolumn{7}{p{0.95\\columnwidth}}{\\footnotesize Gold list "
        "$N=32$ per clip; one clip per language, single run, \\texttt{Qwen/Qwen3.5-4B} "
        "in 4-bit. Latency was 71--81\\,s per call and is reported in the text, not here, "
        "because it is dominated by local decoding rather than by the strategy. "
        "No glossary-RAG row exists: the retrieval arm consumed "
        "\\texttt{data/gold\\_terms.json}, the very artefact used for scoring, so it "
        "measures leakage instead of prompting; the harness now requires a held-out "
        "\\texttt{data/glossary\\_<CLIP>.json}, which has never been annotated.}"
    )
    lines.append("\\end{tabular}")
    lines.append(
        "\\caption{Measured effect of prompting strategy on closed-gold terminology "
        "extraction. The two-arm comparison is a single-clip probe, not a strategy "
        "benchmark.}"
    )
    lines.append("% AUTOGEN-END")
    lines.append("\\label{tab:prompt_strat}")
    lines.append("\\end{table}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--in", dest="src", type=Path, default=DEFAULT_IN)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    rows = load_rows(args.src)
    if not rows:
        raise SystemExit("no measured rows found")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows), encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
