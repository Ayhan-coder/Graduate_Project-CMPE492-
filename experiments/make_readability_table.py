"""make_readability_table.py: regenerate paper/tables/readability.tex from a measured run.

Input is outputs/readability_eval.json, produced by:

    python experiments/eval_semantic.py \
        --jsonl experiments/outputs/llm-20261010-214422.jsonl \
                experiments/outputs/llm-20261010-214130.jsonl \
                experiments/outputs/ablation-all.jsonl \
        --format json --out experiments/outputs/readability_eval.json

Two claims the previous hand-written table made and this one cannot:
  * "BERTScore" -- the optional ``bert_score`` package is not installed, so
    eval_semantic.compute_bert_score() falls back to a character-trigram cosine plus
    word-overlap proxy. The generated column names that proxy for what it is.
  * every explanation lands in the CEFR B1 band -- the measured per-item share inside the
    target band is far below 100%, so the table reports it explicitly.

Turkish target band: Ateşman 50-69 ("Orta Güçlükte"). English target band: Flesch reading
ease 60-70 ("Standard"). Both bands are the ones the paper states as its B1 goal.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TABLES = ROOT.parent / "paper" / "tables"

EVAL_JSON = ROOT / "outputs" / "readability_eval.json"
OUT_TEX = TABLES / "readability.tex"

MODEL_LABEL = {
    "evren/qwen3.8-flash-next": "EVREN Qwen 3.8 Flash",
    "evren/deepseek-v4.1-flash": "EVREN DeepSeek V4.1 Flash",
    "Qwen3.5-4B": "Qwen3.5-4B (local 4-bit)",
}
ORDER = ["evren/qwen3.8-flash-next", "evren/deepseek-v4.1-flash", "Qwen3.5-4B"]


def band(lang: str) -> tuple[float, float, str, str]:
    if lang == "TR":
        return 50.0, 69.0, "Ate\\c{s}man", "Orta G\\\"u\\c{c}l\\\"ukte"
    return 60.0, 70.0, "Flesch", "Standard"


def main() -> None:
    rows = json.loads(EVAL_JSON.read_text(encoding="utf-8"))
    by_model: dict[tuple[str, str], list[dict]] = {}
    for r in rows:
        by_model.setdefault((r["model"], r["lang"]), []).append(r)

    backends = {r.get("similarity_backend", "none") for r in rows}
    if len(backends) != 1:
        raise SystemExit(f"mixed similarity backends in one artifact: {backends}")
    backend = backends.pop()
    is_proxy = backend.startswith("lexical-proxy")

    out_rows = []
    for model in ORDER:
        for lang in ("TR", "EN"):
            cells = by_model.get((model, lang))
            if not cells:
                continue
            n = sum(c["total_terms"] for c in cells)
            matched = sum(c["ref_matched_terms"] for c in cells)
            lo, hi, metric, band_name = band(lang)
            # Weight cell means by term counts to recover the pooled per-item average.
            mean = sum(c["readability_avg"] * c["total_terms"] for c in cells) / n
            in_target = sum(c.get("readability_pct_in_target", 0.0) * c["total_terms"] for c in cells) / n
            sim = sum(c["bert_f1"] * c["ref_matched_terms"] for c in cells) / matched if matched else 0.0
            scores = [c["readability_avg"] for c in cells]
            out_rows.append(
                {
                    "model": MODEL_LABEL.get(model, model),
                    "lang": lang,
                    "metric": metric,
                    "n": n,
                    "mean": mean,
                    "lo": min(scores),
                    "hi": max(scores),
                    "in_target": in_target,
                    "matched": matched,
                    "sim": sim,
                    "band": f"{lo:.0f}--{hi:.0f}",
                    "band_name": band_name,
                    "cells": len(cells),
                }
            )

    sim_head = r"Lexical proxy $F_1$ (\%)" if is_proxy else r"BERTScore $F_1$ (\%)"
    lines = [
        "% GENERATED by experiments/make_readability_table.py -- do not edit by hand.",
        "% Recomputed from outputs/readability_eval.json (eval_semantic.py over the run artifacts).",
        f"% Similarity backend recorded in the artifact: {backend}",
        r"\begin{table}[t]",
        r"\centering",
        r"\renewcommand{\arraystretch}{1.1}",
        r"\small",
        r"\begin{tabular}{llcrrrrrr}",
        r"\toprule",
        r"\textbf{Model} & \textbf{Lang} & \textbf{Index} & \textbf{Expl.} & \textbf{Refs} & \textbf{Mean} & \textbf{Min--Max} & \textbf{In band (\%)} & "
        + sim_head
        + r" \\",
        r"\midrule",
    ]
    for r in out_rows:
        span = f"{r['lo']:.1f}--{r['hi']:.1f}" if r["cells"] > 1 else "--"
        lines.append(
            f"{r['model']} & {r['lang']} & {r['metric']} & {r['n']} & {r['matched']} & {r['mean']:.1f} & "
            f"{span} & {r['in_target']:.1f} & {r['sim']:.1f} \\\\"
        )
    proxy_note = (
        r"The similarity column is a \emph{lexical proxy} (character-trigram cosine blended with"
        r" word-set precision/recall), \emph{not} contextual-embedding BERTScore: the optional"
        r" \texttt{bert\_score} package is absent from this environment and"
        r" \texttt{eval\_semantic.compute\_bert\_score} therefore takes its documented fallback"
        r" branch. Treat it as a surface-overlap measure."
        if is_proxy
        else r"The similarity column is contextual-embedding BERTScore."
    )
    cell_span = f"{min(r['cells'] for r in out_rows)}--{max(r['cells'] for r in out_rows)}"
    lines += [
        r"\bottomrule",
        r"\multicolumn{9}{p{0.95\columnwidth}}{\footnotesize \textbf{Refs} is the number of emitted"
        r" explanations matched to a curated TDK/Oxford definition, so the similarity column averages"
        r" only that subset while the readability columns cover every explanation. Target pedagogical"
        r" bands are Ate\c{s}man $50$--$69$ (\texttt{Orta G\"u\c{c}l\"ukte}) for Turkish and Flesch"
        r" reading ease $60$--$70$ (\texttt{Standard}) for English. \textbf{In band} is the measured"
        r" share of individual explanations inside that band, so a mean near the band edge is not"
        r" evidence that all output is B1-level. Min--Max spans the per-ASR-feed cell means"
        f" ({cell_span} feeds pooled per model; a single-cell row has no spread to report), which is"
        r" where most of the variation originates. "
        + proxy_note
        + r" No readability or similarity artifact exists for the commercial-API models, whose saved"
        r" outputs are unstructured Markdown rather than the term/explanation schema consumed here,"
        r" so they are omitted rather than estimated.}",
        r"\end{tabular}",
        r"\caption{Measured pedagogical readability of generated explanations and lexical-proxy"
        r" similarity to curated reference definitions.}",
        r"% AUTOGEN-END",
        r"\label{tab:readability}",
        r"\end{table}",
        "",
    ]
    OUT_TEX.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_TEX}")
    for r in out_rows:
        print(
            f"  {r['model']:<26}{r['lang']}  n={r['n']:<5} mean={r['mean']:.1f} "
            f"[{r['lo']:.1f}-{r['hi']:.1f}] in-band={r['in_target']:.1f}% sim={r['sim']:.1f} "
            f"refs={r['matched']}/{r['n']}"
        )
    print(f"  similarity backend: {backend}")


if __name__ == "__main__":
    main()
