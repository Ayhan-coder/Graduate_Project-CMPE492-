"""Aggregate LLM inference latency from run artifacts into paper/tables/llm_latency.tex.

Does not invent numbers: every cell is recomputed from a JSONL artifact on disk. If a
model has no logged latency it is omitted rather than filled in.

Usage:
    python make_llm_latency_table.py
"""

from __future__ import annotations

import json
import statistics as st
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT_DIR = ROOT / "outputs"
TEX_DIR = ROOT.parent / "paper" / "tables"


def lang_code(raw: str) -> str | None:
    v = str(raw).lower()
    if v.startswith("turk") or v == "tr":
        return "tr"
    if v.startswith("engl") or v == "en":
        return "en"
    return None


def read_jsonl(path: Path):
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def collect() -> dict[tuple[str, str], list[float]]:
    buckets: dict[tuple[str, str], list[float]] = defaultdict(list)

    for name in ("llm-20261010-214422.jsonl", "llm-20261010-214130.jsonl"):
        for r in read_jsonl(OUT_DIR / name):
            label = "EVREN Qwen 3.8 Flash" if "qwen3.8" in str(r.get("model")) else "EVREN DeepSeek V4.1 Flash"
            lc = lang_code(r.get("lang"))
            if lc and isinstance(r.get("latency_s"), (int, float)):
                buckets[(label, lc)].append(float(r["latency_s"]))

    for path in sorted((OUT_DIR / "pilot_baseline" / "semantic_logs").glob("*.jsonl")):
        for r in read_jsonl(path):
            lc = lang_code(r.get("lang"))
            model = {"gpt-4.1": "GPT-4.1 (commercial API)", "gpt-4o-mini": "GPT-4o-mini (commercial API)"}.get(
                str(r.get("model"))
            )
            if model and lc and isinstance(r.get("latency_s"), (int, float)):
                buckets[(model, lc)].append(float(r["latency_s"]))

    # Local open-weight models: latency depends strongly on which ASR hypothesis they were
    # fed, so the ablation run is reported per ASR source instead of pooled.
    for r in read_jsonl(OUT_DIR / "ablation-20260905-143731.jsonl"):
        lc = lang_code(r.get("lang"))
        if lc and isinstance(r.get("latency_s"), (int, float)):
            buckets[(f"Qwen3.5-4B (local 4-bit, fed {r.get('asr_model')})", lc)].append(float(r["latency_s"]))

    for r in read_jsonl(OUT_DIR / "llm-20260913-210556.jsonl"):
        lc = lang_code(r.get("lang"))
        if lc and isinstance(r.get("latency_s"), (int, float)):
            buckets[("Qwen3.5-9B (local, host-offloaded)", lc)].append(float(r["latency_s"]))

    return buckets


ORDER = [
    "EVREN Qwen 3.8 Flash",
    "EVREN DeepSeek V4.1 Flash",
    "GPT-4o-mini (commercial API)",
    "GPT-4.1 (commercial API)",
    "Qwen3.5-4B (local 4-bit, fed openai/whisper-large-v3)",
    "Qwen3.5-4B (local 4-bit, fed openai/whisper-medium)",
    "Qwen3.5-4B (local 4-bit, fed openai/whisper-large-v3-turbo)",
    "Qwen3.5-9B (local, host-offloaded)",
]


def main() -> None:
    buckets = collect()
    lines = [
        "% GENERATED by experiments/make_llm_latency_table.py -- do not edit by hand.",
        "% Every value is recomputed from outputs/*.jsonl and outputs/pilot_baseline/semantic_logs/*.jsonl.",
        r"\begin{table}[t]",
        r"\centering",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\small",
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"\textbf{Model} & \textbf{Lang} & \textbf{$n$} & \textbf{Mean (s)} & \textbf{s.d.} & \textbf{Min} & \textbf{Max} \\",
        r"\midrule",
    ]
    label_tex = {
        "GPT-4o-mini (commercial API)": "GPT-4o-mini (API)",
        "GPT-4.1 (commercial API)": "GPT-4.1 (API)",
        "Qwen3.5-4B (local 4-bit, fed openai/whisper-large-v3)": r"Qwen3.5-4B local 4-bit $\cdot$ Large-v3 feed",
        "Qwen3.5-4B (local 4-bit, fed openai/whisper-medium)": r"Qwen3.5-4B local 4-bit $\cdot$ Medium feed",
        "Qwen3.5-4B (local 4-bit, fed openai/whisper-large-v3-turbo)": r"Qwen3.5-4B local 4-bit $\cdot$ Turbo feed",
        "Qwen3.5-9B (local, host-offloaded)": r"Qwen3.5-9B local $\cdot$ offloaded",
    }
    seen = set()
    for label in ORDER:
        for lang in ("tr", "en"):
            if (label, lang) not in buckets:
                continue
            seen.add((label, lang))
            v = buckets[(label, lang)]
            sd = st.stdev(v) if len(v) > 1 else 0.0
            name = label_tex.get(label, label)
            lines.append(
                f"{name} & {lang.upper()} & {len(v)} & {st.mean(v):.2f} & {sd:.2f} & {min(v):.2f} & {max(v):.2f} \\\\"
            )
    for (label, lang), v in sorted(buckets.items()):
        if (label, lang) in seen:
            continue
        sd = st.stdev(v) if len(v) > 1 else 0.0
        lines.append(
            f"{label_tex.get(label, label)} & {lang.upper()} & {len(v)} & {st.mean(v):.2f} & {sd:.2f} & {min(v):.2f} & {max(v):.2f} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{Measured per-request LLM latency, recomputed from the run artifacts. $n$ is the",
        r"number of logged clip-level calls, so EVREN rows cover 3 Turkish and 4 English clips each.",
        r"Commercial-API rows come from the historical CPU pilot's saved response logs; the local",
        r"Qwen3.5-4B rows are split by which ASR hypothesis was fed in, because that choice dominates",
        r"the variance (s.d.\ up to $132$\,s).} % AUTOGEN-END",
        r"\label{tab:llmlat}",
        r"\end{table}",
    ]
    TEX_DIR.mkdir(parents=True, exist_ok=True)
    out = TEX_DIR / "llm_latency.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines)} lines)")
    for (label, lang), v in sorted(buckets.items()):
        print(f"  {label:52s} {lang} n={len(v)} mean={st.mean(v):.2f}")


if __name__ == "__main__":
    main()
