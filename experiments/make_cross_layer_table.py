"""Emit paper/tables/cross_layer_measured.tex from outputs/cross_layer_curve.json.

Only the MEASURED rows (real ASR hypothesis fed to the fixed LLM) are tabulated here.
The synthetic ladder is excluded because run_cross_layer_curve.py, in its default mode,
samples the gold list directly instead of calling the LLM -- it is a degradation model,
not a measurement. See the note in the generated caption.

Usage:
    python make_cross_layer_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CURVE = ROOT / "outputs" / "cross_layer_curve.json"
TEX_DIR = ROOT.parent / "paper" / "tables"


def main() -> None:
    rows = json.loads(CURVE.read_text(encoding="utf-8"))
    measured = [r for r in rows if not r.get("is_synthetic")]
    simulated = [r for r in rows if r.get("is_synthetic")]
    if not measured:
        raise SystemExit(f"no measured rows in {CURVE}")

    def short(m: str) -> str:
        return (
            m.replace("openai/", "")
            .replace("Qwen/", "")
            .replace("nvidia/", "")
            .replace("-hf", "")
            .replace("-3.5-asr-streaming", " 3.5")
            .replace("whisper-large-v3-turbo-turkish", "Turkish Turbo")
        )

    lines = [
        "% GENERATED by experiments/make_cross_layer_table.py from outputs/cross_layer_curve.json",
        "% -- do not edit by hand. Measured rows only; see cross_layer_curve.json for the modelled ladder.",
        r"\begin{table}[t]",
        r"\centering",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\small",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"\textbf{ASR hypothesis fed to \texttt{Qwen3.5-4B}} & \textbf{Clip} & "
        r"\textbf{WER} & \textbf{$P$} & \textbf{$R$} & \textbf{$F_1$} \\",
        r"\midrule",
    ]

    for lang in ("TR", "EN"):
        sub = sorted(
            (r for r in measured if r["lang"].upper() == lang), key=lambda r: r["wer_norm"]
        )
        for i, r in enumerate(sub):
            sep = r"\midrule" if i == len(sub) - 1 and lang == "TR" else ""
            lines.append(
                f"{short(str(r['asr_model']))} & {r['clip']} & {r['wer_norm']:.3f} & "
                f"{r['precision']:.3f} & {r['recall']:.3f} & {r['f1']:.3f} \\\\ {sep}"
            )

    tr0 = next(r for r in simulated if r["lang"].upper() == "TR" and r["target_wer"] == 0.4)
    en0 = next(r for r in simulated if r["lang"].upper() == "EN" and r["target_wer"] == 0.4)
    tr40 = next(r for r in simulated if r["lang"].upper() == "TR" and r["target_wer"] == 0.4)
    en40 = next(r for r in simulated if r["lang"].upper() == "EN" and r["target_wer"] == 0.4)
    caption = (
        r"\caption{\textbf{Measured} terminology extraction over real ASR hypotheses "
        r"(closed gold list, 32 terms per clip, one clip per language, so no cell is a "
        r"population estimate). WER is the normalised rate of the fed transcript. Across "
        r"these points Turkish $F_1$ spans $0.238$--$0.439$ and English $F_1$ spans "
        r"$0.565$--$0.679$, and the ordering is not monotone in WER. For contrast, the "
        r"analytical ladder modelled in Fig.~\ref{fig:cross_layer_curve} reaches "
        r"$F_1=1.000$ at $0\%$ WER by construction and falls only to "
        + f"${tr40['f1']:.3f}$ (TR) and ${en40['f1']:.3f}$ (EN)"
        + r" at $40\%$ injected error; it never invokes the LLM.}"
    )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        caption,
        r"\label{tab:cross-layer}",
        r"\end{table}",
    ]

    TEX_DIR.mkdir(parents=True, exist_ok=True)
    out = TEX_DIR / "cross_layer_measured.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(measured)} measured, {len(simulated)} modelled rows)")


if __name__ == "__main__":
    main()
