"""make_judge_validation_table.py: rebuild paper/tables/llm_judge.tex from label sheets.

What is actually on disk:
    annotation/labels_a1.csv   annotator 1, 233 term-explanation pairs (6 Whisper cells)
    annotation/labels_a2.csv   annotator 2, 115 pairs, all also present in labels_a1.csv

So the reproducible agreement statistic is *inter-annotator* (human vs human) agreement on
the double-labelled subset. The previously published table claimed those same numbers came
from validating the automated LLM judge against labels_a1.csv, but no per-item judge
predictions were ever stored, so that comparison cannot be recomputed by anyone, including
the authors. This script therefore emits the human/human agreement it can verify and keeps
the two dimensions named R and D exactly as the protocol defines them.

Run:  python experiments/make_judge_validation_table.py
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TABLES = ROOT.parent / "paper" / "tables"

A1 = ROOT / "annotation" / "labels_a1.csv"
A2 = ROOT / "annotation" / "labels_a2.csv"
OUT_TEX = TABLES / "llm_judge.tex"
OUT_JSON = ROOT / "outputs" / "rater_agreement.json"


def load(path: Path) -> dict[str, tuple[int, int]]:
    out: dict[str, tuple[int, int]] = {}
    with path.open(encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            try:
                out[row["item_id"]] = (int(row["R"]), int(row["D"]))
            except (KeyError, TypeError, ValueError):
                continue
    return out


def agreement(pairs: list[tuple[int, int]]) -> dict[str, float]:
    n = len(pairs)
    po = sum(1 for a, b in pairs if a == b) / n
    p1 = sum(a for a, _ in pairs) / n
    p2 = sum(b for _, b in pairs) / n
    pe = p1 * p2 + (1 - p1) * (1 - p2)
    kappa = (po - pe) / (1 - pe) if pe < 1 else 1.0
    return {
        "n": n,
        "po": round(po, 4),
        "pe": round(pe, 4),
        "kappa": round(kappa, 4),
        "pabak": round(2 * po - 1, 4),
        "prevalence_r1": round(p1, 4),
        "prevalence_r2": round(p2, 4),
        "bias": round(abs(p1 - p2), 4),
    }


def main() -> None:
    a1, a2 = load(A1), load(A2)
    common = sorted(set(a1) & set(a2))
    if not common:
        raise SystemExit("labels_a1.csv and labels_a2.csv share no item_id; nothing to score")

    stats = {
        "R": agreement([(a1[i][0], a2[i][0]) for i in common]),
        "D": agreement([(a1[i][1], a2[i][1]) for i in common]),
        "n_a1": len(a1),
        "n_a2": len(a2),
        "n_common": len(common),
        "source": {"a1": A1.name, "a2": A2.name},
    }
    OUT_JSON.write_text(json.dumps(stats, indent=2, ensure_ascii=False), encoding="utf-8")

    def row(dim: str, label: str) -> str:
        s = stats[dim]
        return (
            f"{label} & {s['n']} & {s['po']:.3f} & {s['pe']:.3f} & "
            f"{s['kappa']:.3f} & {s['pabak']:.3f} & {100 * s['prevalence_r1']:.1f}\\% / "
            f"{100 * s['prevalence_r2']:.1f}\\% \\\\"
        )

    lines = [
        "% GENERATED by experiments/make_judge_validation_table.py -- do not edit by hand.",
        "% Recomputed from annotation/labels_a1.csv x annotation/labels_a2.csv (double-labelled subset).",
        r"\begin{table}[t]",
        r"\centering",
        r"\renewcommand{\arraystretch}{1.1}",
        r"\small",
        r"\begin{tabular}{@{}lcccccc@{}}",
        r"\toprule",
        r"\textbf{Dimension} & \textbf{$n$} & \textbf{$P_o$} & \textbf{$P_e$} & \textbf{Cohen's $\kappa$} & \textbf{PABAK} & \textbf{Pos.\ prev.\ (A1/A2)} \\",
        r"\midrule",
        row("R", "Context-consistency ($R$)"),
        row("D", "Beginner suitability ($D$)"),
        r"\bottomrule",
        r"\multicolumn{7}{p{0.95\columnwidth}}{\footnotesize Two-human agreement over the",
        rf"{stats['n_common']} term--explanation pairs that appear in both annotation sheets",
        r"(\texttt{labels\_a1.csv}, \texttt{labels\_a2.csv}); the remaining",
        rf"{stats['n_a1'] - stats['n_common']} pairs of annotator~1's {stats['n_a1']}-pair sheet are",
        r"single-rated and cannot contribute to agreement. $D$ reaches perfect agreement because",
        r"both raters accept almost every explanation ($\approx97\%$ positive prevalence), which also",
        r"drives $P_e$ to $0.949$; PABAK is reported to keep the prevalence paradox visible rather",
        r"than to upgrade the $\kappa$ figure. \textbf{Caveat:} an earlier version of this table",
        r"presented these rows as automated-judge versus human validation. No per-item judge",
        r"predictions were stored, so that comparison is not reproducible and is not claimed here.",
        r"The judge's own per-item output is released only for the 2026 ASR checkpoints and the",
        r"two EVREN models (\texttt{labels\_ablation\_real\_judge.csv},",
        r"\texttt{labels\_evren\_judge.csv}), and those tables name it as the rating source.}",
        r"\end{tabular}",
        r"\caption{Inter-annotator reliability of the binary $R$/$D$ rubric on the double-labelled",
        r"subset of the pilot annotation.}",
        r"% AUTOGEN-END",
        r"\label{tab:llm_judge}",
        r"\end{table}",
        "",
    ]
    OUT_TEX.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_TEX} and {OUT_JSON}")
    for dim in ("R", "D"):
        s = stats[dim]
        print(f"  {dim}: n={s['n']} Po={s['po']:.4f} Pe={s['pe']:.4f} kappa={s['kappa']:.4f} PABAK={s['pabak']:.4f}")


if __name__ == "__main__":
    main()
